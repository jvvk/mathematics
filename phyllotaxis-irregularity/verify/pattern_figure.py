"""Figure 1 of the paper, drawn from the simulator (independent_stack.py), not by hand.

Two runs from F(beta=0.523, eps=0.005), every disk of diameter b0 + c y (seed_convention.consistent_front):
c = -0.0025 (eps/|c| = 2, Fibonacci) and c = -0.00125 (ratio 4, pentagon). For each run, stop at the end of the step-two burst (the pentagon, or the third triangle of
step two), and write TikZ for the disks in a height window below the last placed disk: grey = older
disks, outlined = triangle disks of step two, black = pentagon disk, thick polyline = front.
Output: ../paper/fig_pattern_<tag>.tex (included by paper.tex) and a summary on stdout.
"""

from __future__ import annotations

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from independent_stack import Stack
from seed_convention import consistent_front

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "paper")


def run(beta: float, eps: float, c: float, max_steps: int):
    pts, b = consistent_front(beta, eps, c)
    S = Stack(pts, b, c)
    kinds: dict[int, str] = {}
    step2_started = False
    for n in range(1, max_steps + 1):
        before = S.parastichy()
        dl = S.step()
        k = {1: "T", 0: "R", -1: "P"}.get(dl, "X")
        kinds[len(S.disks) - 1] = k
        if k == "T" and before[0] == 3:
            step2_started = True
        if step2_started and (k == "P" or S.parastichy() == (3, 5)):
            return S, kinds, n
    raise RuntimeError("burst not reached")


def tikz(
    S: Stack, kinds: dict[int, str], tag: str, window: float, burst_ids: set[int]
) -> str:
    top = S.disks[-1][1]
    lo = top - window
    lines = [f"% generated by verify/pattern_figure.py ({tag})"]
    for i, (x, y, d) in enumerate(S.disks):
        if not (lo - d <= y <= top + d):
            continue
        for s in (0.0, 1.0):
            X = x + s
            if not (-0.05 <= X <= 1.55):
                continue
            k = kinds.get(i)
            if i in burst_ids and k == "P":
                style = "fill=black"
            elif i in burst_ids and k == "T":
                style = "fill=white,thick"
            else:
                style = "fill=black!10"
            lines.append(
                f"\\draw[{style}] ({X:.4f},{y - lo:.4f}) circle ({d / 2:.4f});"
            )
    F = S.front + [S.front[0]]
    for s in (0.0, 1.0):
        pts = []
        for j, i in enumerate(F):
            x, y, _ = S.disks[i]
            X = x + s + (1.0 if j == len(F) - 1 else 0.0)
            pts.append(f"({X:.4f},{y - lo:.4f})")
        lines.append("\\draw[very thick] " + " -- ".join(pts) + ";")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    beta, eps = 0.523, 0.005
    for c, tag in ((-0.0025, "clean"), (-0.00125, "break")):
        S, kinds, n = run(beta, eps, c, max_steps=6000)
        # step-two burst disks: the triangles of step two and the pentagon, i.e. the last non-rhombic events
        ids = sorted(kinds)
        burst = {i for i in ids[-12:] if kinds[i] in ("T", "P")}
        with open(os.path.join(OUT, f"fig_pattern_{tag}.tex"), "w") as f:
            f.write(tikz(S, kinds, tag, window=1.0, burst_ids=burst))
        ev = [(i, kinds[i]) for i in sorted(burst)]
        print(
            f"c={c} ({tag}): stopped at step {n}, parastichy {S.parastichy()}, burst {ev}, "
            f"diameter {S.disks[-1][2]:.4f}"
        )
